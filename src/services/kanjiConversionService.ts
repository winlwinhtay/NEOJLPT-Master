/**
 * Extract candidates for a typed kana query or sentence suffix
 */
export function getKanjiCandidates(
  fullText: string,
  cursorPosition?: number
): {
  matchedWord: string;
  startIndex: number;
  endIndex: number;
  candidates: string[];
}[] {
  if (!fullText) return [];

  const textToScan =
    cursorPosition !== undefined ? fullText.slice(0, cursorPosition) : fullText;

  // Find candidate matches by checking suffix fragments up to 15 characters
  const results: {
    matchedWord: string;
    startIndex: number;
    endIndex: number;
    candidates: string[];
  }[] = [];

  const maxLen = Math.min(textToScan.length, 18);
  for (let len = maxLen; len >= 1; len--) {
    const chunk = textToScan.slice(-len);
    const trimmed = chunk.trim();
    if (!trimmed) continue;

    if (KANJI_DICTIONARY[trimmed]) {
      results.push({
        matchedWord: trimmed,
        startIndex: textToScan.length - len,
        endIndex: textToScan.length,
        candidates: KANJI_DICTIONARY[trimmed],
      });
      break;
    }
  }

  return results;
}

/**
 * Direct dictionary lookup for an exact word
 */
export function lookupWordCandidates(word: string): string[] {
  const norm = word.trim();
  if (KANJI_DICTIONARY[norm]) {
    return KANJI_DICTIONARY[norm];
  }
  return [norm];
}
